"""Определение региона по названию медорганизации.

В «Направлениях» и ЭРСБ регион есть только внутри названия организации
(«…управления здравоохранения Туркестанской области»), поэтому восстанавливаем
его сопоставлением по характерным корням. Канонические названия — как на
портале open data (оттуда же берётся список 20 регионов в «Отказах»).
"""
import re

# (каноничное название, корни для поиска в нижнем регистре)
REGION_PATTERNS = [
    ("г. Астана", ["астан"]),
    ("Алматы г.а.", ["алматы", "г.алматы"]),
    ("г. Шымкент", ["шымкент"]),
    ("Туркестанская область", ["туркестан"]),
    ("Жамбылская область", ["жамбыл"]),
    ("Алматинская область", ["алматин"]),
    ("Павлодарская область", ["павлодар"]),
    ("Карагандинская область", ["карагандин", "караганда"]),
    ("Восточно-Казахстанская область", ["восточно-казахстан"]),
    ("Область Абай", ["абайск", "область абай", "области абай"]),
    ("Северо-Казахстанская область", ["северо-казахстан"]),
    ("Акмолинская область", ["акмолин"]),
    ("Кызылординская область", ["кызылорд"]),
    ("Мангистауская область", ["мангистаус"]),
    ("Западно-Казахстанская область", ["западно-казахстан"]),
    ("Атырауская область", ["атырау"]),
    ("Костанайская область", ["костанай"]),
    ("Актюбинская область", ["актюб"]),
    ("Область Жетісу", ["жетісу", "жетису"]),
    ("Область Ұлытау", ["ұлытау", "улытау"]),
]

# Справочник кодов регионов очереди (KATO 2023). Выверен по данным: голосование
# «код → регион больниц» даёт те же имена для 17 из 20 кодов; коды 33 (Жетісу) и
# 62 (Ұлытау) голосованием смещаются на соседние области — пациенты оттуда едут
# лечиться в Алматинскую/Карагандинскую, где больше стационаров.
REGION_CODE_NAMES = {
    "10": "Абайская область", "11": "Акмолинская область", "15": "Актюбинская область",
    "19": "Алматинская область", "23": "Атырауская область", "27": "Западно-Казахстанская область",
    "31": "Жамбылская область", "33": "Область Жетісу", "35": "Карагандинская область",
    "39": "Костанайская область", "43": "Кызылординская область", "47": "Мангистауская область",
    "55": "Павлодарская область", "59": "Северо-Казахстанская область", "61": "Туркестанская область",
    "62": "Область Ұлытау", "63": "Восточно-Казахстанская область", "71": "г. Астана",
    "75": "Алматы г.а.", "79": "г. Шымкент",
}


def region_name(code: str) -> str:
    return REGION_CODE_NAMES.get(str(code), f"код {code}")


_CACHE: dict[str, str | None] = {}


def parse_region(mo_name: str) -> str | None:
    """Регион по названию МО или None, если определить не удалось."""
    if not isinstance(mo_name, str) or not mo_name.strip():
        return None
    if mo_name in _CACHE:
        return _CACHE[mo_name]
    low = mo_name.lower().replace("ұ", "у").replace("і", "и")
    region = None
    for canonical, stems in REGION_PATTERNS:
        for stem in stems:
            stem_norm = stem.lower().replace("ұ", "у").replace("і", "и")
            if stem_norm in low:
                region = canonical
                break
        if region:
            break
    _CACHE[mo_name] = region
    return region


def add_region_column(df, name_col: str = "hospital_mo", out_col: str = "region"):
    """Добавить в датафрейм колонку региона, распарсив названия организаций."""
    regions = df[name_col].astype(str).map(parse_region)
    df[out_col] = regions.astype("category")
    return df
